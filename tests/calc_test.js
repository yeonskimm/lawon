// 법ON 계산 도구 검사: 월급↔시급 환산·연차 발생일수
// 기대값은 코드가 아니라 법령 산식으로 손계산(분수 계산으로 교차 확인)한 값
//  - 월급 ↔ 시급: 월 기준시간(주 40시간 209시간, 고용노동부 고시 월 환산 기준)으로 나누고 곱함
//  - 근로기준법 제60조①②④, 민법 제157조·제160조(기간 계산), 대법원 2021. 10. 14. 선고 2021다227100(1년 근로 다음 날 재직)
// 사용: node tests/calc_test.js index.html
const fs=require('fs'),vm=require('vm');
const html=fs.readFileSync(process.argv[2]||'index.html','utf8');
const a=html.indexOf('/*CALC_START*/'), b=html.indexOf('/*CALC_END*/');
if(a<0||b<0){console.log('FAIL  CALC 표시를 찾지 못함');process.exit(1);}
const C=vm.runInNewContext(html.slice(a,b)+'\n;({wgConv,wgHours,alCalc,MWT})',{});
let fail=0,cnt=0;
const chk=(name,got,exp)=>{cnt++; const ok=JSON.stringify(got)===JSON.stringify(exp); if(!ok)fail++; if(!ok||process.env.VERBOSE)console.log((ok?'PASS':'FAIL')+'  '+name+'  기대 '+JSON.stringify(exp)+' / 실제 '+JSON.stringify(got));};

// ── 연도표(고용노동부 고시) ──
chk('2023년 9,620원',C.MWT.find(x=>x.y===2023).v,9620); chk('2024년 9,860원',C.MWT.find(x=>x.y===2024).v,9860);
chk('2025년 10,030원',C.MWT.find(x=>x.y===2025).v,10030); chk('2026년 10,320원',C.MWT.find(x=>x.y===2026).v,10320);
chk('2027년 10,700원',C.MWT.find(x=>x.y===2027).v,10700);
const V=(dir,amt,hrs)=>C.wgConv({dir,amt,hrs});
// ── 월급 ↔ 시급 환산(월 기준시간 기본 209) ──
chk('고시 월 환산액 2,156,880 ÷ 209 = 10,320',V('m2h',2156880,209).out,10320);
chk('10,320 × 209 = 2,156,880',V('h2m',10320,209).out,2156880);
chk('10,700 × 209 = 2,236,300(2027 고시)',V('h2m',10700,209).out,2236300);
chk('9,620 × 209 = 2,010,580(2023 고시)',V('h2m',9620,209).out,2010580);
chk('2,156,879 ÷ 209 → 10,319(원 미만 버림)',V('m2h',2156879,209).out,10319);
chk('2,156,000 ÷ 209 → 10,315',V('m2h',2156000,209).out,10315);
chk('2,100,000 ÷ 209 → 10,047',V('m2h',2100000,209).out,10047);
const H=(wh,hh)=>C.wgHours(wh,hh==null?null:hh);
// ── 1주 소정근로시간 → 주휴 → 월 기준시간(반올림) ──
chk('주 40h → 주휴 8, 208.57 → 209',[H(40).hh,H(40).hrs],[8,209]);
chk('주 20h → 주휴 4, 104.29 → 104',[H(20).hh,H(20).hrs],[4,104]);
chk('주 30h → 주휴 6, 156.43 → 156',[H(30).hh,H(30).hrs],[6,156]);
chk('주 35h → 주휴 7, 182.5 → 183(반올림)',[H(35).hh,H(35).hrs],[7,183]);
chk('주 15h → 주휴 3, 78.21 → 78',[H(15).hh,H(15).hrs],[3,78]);
chk('주 14h → 주휴 없음, 60.83 → 61',[H(14).hh,H(14).hrs],[0,61]);
chk('주 44h → 주휴 최대 8, 225.95 → 226',[H(44).hh,H(44).hrs],[8,226]);
chk('주휴 직접 0 → 173.81 → 174',[H(40,0).hh,H(40,0).hrs],[0,174]);
chk('주 소정 없음 → 오류',!!H(0).err,true);
chk('20h 104시간: 10,320 × 104 = 1,073,280',V('h2m',10320,104).out,1073280);
chk('1,073,280 ÷ 104 = 10,320',V('m2h',1073280,104).out,10320);
chk('소수 기준시간 곱은 원 미만 올림: 10,320 × 104.29 = 1,076,272.8 → 1,076,273',V('h2m',10320,104.29).out,1076273);
// 반올림 전 시간(시행령 산식)으로 나눈 값 — 반올림 방향에 따라 최저임금을 사이에 두고 갈리는 예
chk('주 20h 1,075,000 ÷ 104 = 10,336 / ÷ 104.2857 = 10,308',[V('m2h',1075000,H(20).hrs).out,V('m2h',1075000,H(20).raw).out],[10336,10308]);
chk('주 40h 2,156,000 ÷ 209 = 10,315 / ÷ 208.5714 = 10,336.98 → 10,336(버림)',[V('m2h',2156000,H(40).hrs).out,V('m2h',2156000,H(40).raw).out],[10315,10336]);
chk('주 40h 10,320 × 208.5714 = 2,152,457.1 → 2,152,458',V('h2m',10320,H(40).raw).out,2152458);
chk('기준시간 없음 → 오류',!!V('m2h',2000000,0).err,true);
chk('금액 없음 → 오류',!!V('h2m',0,209).err,true);

// ── 연차 발생일수(입사일 기준) ──
const L=(s,e)=>C.alCalc(s,e);
r=L('2025-01-01','2025-01-01'); chk('입사 당일 → 1일 근무, 0일',[r.dur,r.moN,r.k],[{y:0,m:0,d:1},0,0]);
r=L('2025-01-01','2025-01-31'); chk('1개월 마친 날 → 아직 0일(다음 날 발생)',[r.dur,r.moN,r.nextMo],[{y:0,m:1,d:0},0,'2025-02-01']);
r=L('2025-01-01','2025-02-01'); chk('1개월 다음 날 → 1일',r.moN,1);
r=L('2025-01-15','2025-03-20'); chk('1.15 입사 3.20 → 2개월 6일, 2일',[r.dur,r.moN],[{y:0,m:2,d:6},2]);
r=L('2025-01-01','2025-12-31'); chk('1년 마친 날 → 11일, 15일은 아직(다음 날 재직 필요)',[r.moN,r.k,r.doneNot,r.next],[11,0,true,{date:'2026-01-01',days:15}]);
chk('1년 마친 날 → 근속 1년 0개월 0일',r.dur,{y:1,m:0,d:0});
r=L('2025-01-01','2026-01-01'); chk('1년 다음 날 → 15일(2026-01-01~2026-12-31)',[r.k,r.cur],[1,{days:15,from:'2026-01-01',to:'2026-12-31'}]);
chk('1년 다음 날 → 다음 발생 2027-01-01 15일',r.next,{date:'2027-01-01',days:15});
r=L('2025-01-01','2027-01-01'); chk('2년 → 15일, 다음 16일',[r.cur.days,r.next.days],[15,16]);
r=L('2025-01-01','2028-01-01'); chk('3년 → 16일',[r.k,r.cur.days],[3,16]);
r=L('2025-01-01','2029-01-01'); chk('4년 → 16일',r.cur.days,16);
r=L('2025-01-01','2030-01-01'); chk('5년 → 17일',r.cur.days,17);
r=L('2000-01-01','2020-12-31'); chk('20년 → 24일',[r.k,r.cur.days],[20,24]);
r=L('2000-01-01','2021-01-01'); chk('21년 → 25일',[r.k,r.cur.days],[21,25]);
r=L('2000-01-01','2023-01-01'); chk('23년 → 25일 한도',r.cur.days,25);
r=L('2024-01-31','2024-02-29'); chk('1.31 입사: 2월 말일에 1개월 만료 → 3.1 발생',[r.mo[0],r.moN],['2024-03-01',0]);
r=L('2024-01-31','2024-03-01'); chk('1.31 입사 3.1 → 1일',r.moN,1);
chk('1.31 입사 2개월째 → 3.31 발생',L('2024-01-31','2024-03-31').mo[1],'2024-03-31');
r=L('2024-02-29','2025-02-28'); chk('윤일 입사: 2025.2.28 만료, 15일은 3.1(아직)',[r.k,r.doneNot,r.first],[0,true,'2025-03-01']);
r=L('2024-02-29','2025-03-01'); chk('윤일 입사 2025.3.1 → 15일',[r.k,r.cur&&r.cur.days],[1,15]);
r=L('2024-01-02','2025-01-01'); chk('2024.1.2 입사 2025.1.1 → 1년 마침(366일), 15일은 1.2',[r.dur,r.k,r.doneNot],[{y:1,m:0,d:0},0,true]);
r=L('2025-03-10','2025-09-26'); chk('첫해 월 단위 휴가 사용 기간 끝 2026-03-09',r.firstEnd,'2026-03-09');
r=L('2024-02-29','2024-03-01'); chk('윤일 입사 → 1년 되는 날 2025-02-28',r.firstEnd,'2025-02-28');
r=L('2020-12-31','2026-09-26'); chk('2020.12.31 입사 → 근속 5년, 17일(2025.12.31~2026.12.30)',[r.k,r.cur],[5,{days:17,from:'2025-12-31',to:'2026-12-30'}]);
chk('기준일이 입사일보다 앞 → 오류',!!L('2025-05-01','2025-04-30').err,true);
chk('없는 날짜 → 오류',!!L('2025-02-30','2025-04-30').err,true);

console.log((fail?'실패 '+fail+'건':'모두 통과')+' ('+cnt+'건)');
process.exit(fail?1:0);
